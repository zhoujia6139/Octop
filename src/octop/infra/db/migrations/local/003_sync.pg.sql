CREATE TABLE local_sync_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_id TEXT NOT NULL UNIQUE,
    agent_id TEXT NOT NULL REFERENCES local_agents(agent_id),
    resource_id TEXT NOT NULL,
    kind TEXT NOT NULL,
    revision INTEGER NOT NULL,
    cloud_revision INTEGER NOT NULL DEFAULT 0,
    digest TEXT NOT NULL,
    data TEXT NOT NULL,
    state TEXT NOT NULL DEFAULT 'pending'
);
CREATE TABLE local_sync_outbox (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    operation_id TEXT NOT NULL UNIQUE,
    item_id TEXT NOT NULL REFERENCES local_sync_items(item_id),
    revision INTEGER NOT NULL,
    mutation TEXT NOT NULL,
    state TEXT NOT NULL DEFAULT 'pending',
    error TEXT
);
CREATE TABLE local_sync_chunks (
    digest TEXT NOT NULL,
    offset_bytes BIGINT NOT NULL,
    content BYTEA NOT NULL,
    PRIMARY KEY(digest,offset_bytes)
);
CREATE TABLE local_sync_state (
    key TEXT PRIMARY KEY,
    value TEXT NOT NULL
);
ALTER TABLE local_threads ADD COLUMN restored INTEGER NOT NULL DEFAULT 0;
